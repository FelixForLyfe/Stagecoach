package net.feelix.stagecoach.forge;

import net.fabricmc.fabric.api.gametest.v1.GameTest;
import net.feelix.stagecoach.api.event.DestinationListEvent;
import net.feelix.stagecoach.api.event.JourneyEndedEvent;
import net.feelix.stagecoach.api.event.JourneyPreStartEvent;
import net.feelix.stagecoach.api.event.StopDiscoverEvent;
import net.feelix.stagecoach.gametest.EventGameTests;
import net.feelix.stagecoach.gametest.PackGameTests;
import net.feelix.stagecoach.gametest.StagecoachGameTests;
import net.feelix.stagecoach.gametest.TravelGameTests;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.resources.Identifier;
import net.minecraftforge.eventbus.api.listener.Priority;
import net.minecraftforge.eventbus.api.listener.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.registries.RegisterEvent;

import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.List;
import java.util.Locale;
import java.util.function.Consumer;

/** Dev only: test instances are generated by tools/make_forge_test_instances.py. */
@Mod.EventBusSubscriber(modid = "stagecoach")
public final class ForgeGameTests {
    private ForgeGameTests() {}

    private static final String NAMESPACE = "stagecoach_gametest";
    private static final List<Class<?>> CLASSES = List.of(StagecoachGameTests.class, TravelGameTests.class, PackGameTests.class,
            EventGameTests.class);

    static {
        JourneyPreStartEvent.BUS.addListener(Priority.NORMAL, EventGameTests::onPreStart);
        DestinationListEvent.BUS.addListener(EventGameTests::onList);
        JourneyEndedEvent.BUS.addListener(EventGameTests::onEnded);
        StopDiscoverEvent.BUS.addListener(Priority.NORMAL, EventGameTests::onDiscover);
    }

    @SubscribeEvent
    public static void registerFunctions(RegisterEvent event) {
        event.register(Registries.TEST_FUNCTION, helper -> {
            for (Class<?> cls : CLASSES) {
                for (Method method : cls.getDeclaredMethods()) {
                    if (method.getAnnotation(GameTest.class) == null) continue;
                    helper.register(Identifier.fromNamespaceAndPath(NAMESPACE, snake(cls.getSimpleName()) + "_" + snake(method.getName())), invoker(method));
                }
            }
        });
    }

    /** "TravelGameTests" -> "travel_game_tests", as Fabric names them. */
    private static String snake(String name) {
        return name.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT);
    }

    private static Consumer<GameTestHelper> invoker(Method method) {
        return helper -> {
            try {
                Object target = Modifier.isStatic(method.getModifiers()) ? null : method.getDeclaringClass().getDeclaredConstructor().newInstance();
                method.invoke(target, helper);
            } catch (InvocationTargetException e) {
                if (e.getCause() instanceof RuntimeException r) throw r;
                throw new RuntimeException(e.getCause());
            } catch (ReflectiveOperationException e) {
                throw new RuntimeException(e);
            }
        };
    }
}
